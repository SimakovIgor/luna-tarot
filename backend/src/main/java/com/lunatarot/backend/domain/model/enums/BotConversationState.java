package com.lunatarot.backend.domain.model.enums;

/**
 * Состояние пользователя относительно Mini App. Бот собственного диалога больше не ведёт:
 * имя/ДР/пол собираются внутри Mini App, поэтому достаточно двух значений.
 */
public enum BotConversationState {
    /** Пользователь зашёл в бота, но не завершил онбординг в Mini App. */
    NEW,
    /** Профиль в Mini App заполнен — пользователь готов к ритуалам и попадает в утреннюю рассылку. */
    READY
}
