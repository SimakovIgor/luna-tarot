#!/usr/bin/env bash
# Прогон ТЕКУЩИХ production-промптов Luna через Anthropic API.
# Скрипт держим в синке с ClaudeInterpreter / ClaudeHoroscopeGenerator / ClaudeCompatibilityGenerator.
# Цель: смотреть на ответы при разных входах (нормальный вопрос, абракадабра, английский, эмоциональный, etc).
#
# Использование:
#   ./scripts/prompt-lab.sh           # все сценарии
#   ./scripts/prompt-lab.sh reading   # только расклады
#   ./scripts/prompt-lab.sh horoscope # только гороскопы
#   ./scripts/prompt-lab.sh compat    # только совместимость

set -eo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUTDIR=/tmp/luna-prompts
mkdir -p "$OUTDIR"

set -a; source "$ROOT/.env"; set +a
MODEL="${LLM_MODEL:-claude-haiku-4-5-20251001}"
API_KEY="$ANTHROPIC_API_KEY"

claude_call() {
  local label="$1" system="$2" user="$3" max_tokens="${4:-1024}"
  local outfile="$OUTDIR/$label.txt"
  local body
  body=$(jq -n \
    --arg model "$MODEL" \
    --arg sys "$system" \
    --arg usr "$user" \
    --argjson maxtok "$max_tokens" \
    '{model:$model, max_tokens:$maxtok, system:$sys, messages:[{role:"user",content:$usr}]}')

  local resp
  resp=$(curl -sS https://api.anthropic.com/v1/messages \
    -H "x-api-key: $API_KEY" \
    -H "anthropic-version: 2023-06-01" \
    -H "content-type: application/json" \
    -d "$body")

  local text
  text=$(echo "$resp" | jq -r '.content[]? | select(.type=="text") | .text')
  [[ -z "$text" ]] && text="<<EMPTY>>$(echo "$resp" | jq -c '.error // .')"

  {
    echo "===== $label ====="
    echo "--- SYSTEM ---"; echo "$system"
    echo "--- USER ---"; echo "$user"
    echo "--- OUTPUT (${#text} chars) ---"; echo "$text"
  } > "$outfile"

  echo "── $label (${#text} chars) ──"
  echo "$text"
  echo
}

zod()   { case "$1" in ARIES) echo "Овен";; TAURUS) echo "Телец";; GEMINI) echo "Близнецы";; CANCER) echo "Рак";; LEO) echo "Лев";; VIRGO) echo "Дева";; LIBRA) echo "Весы";; SCORPIO) echo "Скорпион";; SAGITTARIUS) echo "Стрелец";; CAPRICORN) echo "Козерог";; AQUARIUS) echo "Водолей";; PISCES) echo "Рыбы";; *) echo "не указан";; esac; }
lunar() { case "$1" in NEW) echo "новолуние (зерно, замысел)";; WAXING) echo "растущая луна (рост, набор силы)";; FULL) echo "полнолуние (вершина, видимость)";; WANING) echo "убывающая луна (отпускание, завершение)";; *) echo "не указано";; esac; }
gender() { case "$1" in MALE) echo "мужчина";; FEMALE) echo "женщина";; *) echo "пол не указан";; esac; }
agree()  { case "$1" in MALE) echo "рад / родился / готов";; FEMALE) echo "рада / родилась / готова";; *) echo "рад(а) / родился(-ась) / готов(а)";; esac; }

